/**
 * Generates src/types/database.ts (supabase-js `Database` type) by introspecting a throwaway
 * embedded Postgres with all migrations applied. Works offline, no Docker required.
 *   npm run db:types
 * When the Supabase project is linked you may instead use `supabase gen types`.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import EmbeddedPostgres from 'embedded-postgres'
import pg from 'pg'

const root = path.resolve(import.meta.dirname, '..')

const scalar: Record<string, string> = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', date: 'string',
  timestamptz: 'string', timestamp: 'string', time: 'string', interval: 'string', bytea: 'string',
  int2: 'number', int4: 'number', int8: 'number', float4: 'number', float8: 'number', numeric: 'number',
  bool: 'boolean', jsonb: 'Json', json: 'Json', void: 'undefined',
}

async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'habitnest-types-'))
  const port = 56000 + Math.floor(Math.random() * 3000)
  const server = new EmbeddedPostgres({ databaseDir: dir, user: 'postgres', password: 'postgres', port, persistent: false, onLog: () => {} })
  await server.initialise()
  await server.start()
  const db = new pg.Client({ connectionString: `postgres://postgres:postgres@localhost:${port}/postgres` })
  await db.connect()
  try {
    await db.query(fs.readFileSync(path.join(root, 'tests/db/bootstrap.sql'), 'utf8'))
    const mdir = path.join(root, 'supabase/migrations')
    for (const f of fs.readdirSync(mdir).filter((x) => x.endsWith('.sql')).sort()) {
      await db.query(fs.readFileSync(path.join(mdir, f), 'utf8'))
    }

    const enums = (await db.query<{ name: string; values: string[] }>(`
      select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as values
        from pg_type t join pg_enum e on e.enumtypid = t.oid
        join pg_namespace n on n.oid = t.typnamespace
       where n.nspname = 'public' group by t.typname order by t.typname`)).rows
    const enumNames = new Set(enums.map((e) => e.name))

    const tsType = (udt: string): string => {
      if (udt.startsWith('_')) return `${tsType(udt.slice(1))}[]`
      if (enumNames.has(udt)) return `Database['public']['Enums']['${udt}']`
      return scalar[udt] ?? 'unknown'
    }

    const cols = (await db.query<{
      table_name: string; column_name: string; udt_name: string; is_nullable: string; column_default: string | null
    }>(`
      select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default
        from information_schema.columns c
        join pg_tables t on t.tablename = c.table_name and t.schemaname = c.table_schema
       where c.table_schema = 'public'
       order by c.table_name, c.ordinal_position`)).rows

    const tables = new Map<string, typeof cols>()
    for (const c of cols) tables.set(c.table_name, [...(tables.get(c.table_name) ?? []), c])

    const fns = (await db.query<{
      name: string; arg_names: string[] | null; arg_types: string[]; n_defaults: number;
      ret_type: string; retset: boolean; out_names: string[] | null; out_types: string[] | null
    }>(`
      select p.proname as name, p.proargnames as arg_names,
             array(select format_type(t, null) from unnest(p.proargtypes) t) as arg_types,
             p.pronargdefaults as n_defaults,
             (select typname::text from pg_type where oid = p.prorettype) as ret_type, p.proretset as retset,
             array(select n::text from unnest(p.proargnames, p.proargmodes) as x(n, m) where m = 't') as out_names,
             array(select (select typname::text from pg_type where oid = ty) from unnest(p.proallargtypes, p.proargmodes) as x(ty, m) where m = 't') as out_types
        from pg_proc p join pg_namespace n on n.oid = p.pronamespace
       where n.nspname = 'public'
         and (has_function_privilege('authenticated', p.oid, 'execute') or has_function_privilege('service_role', p.oid, 'execute'))
         and p.prorettype <> 'trigger'::regtype
         and p.proname not like '\\_%'
       order by p.proname`)).rows

    const argUdt = async (formatted: string) => {
      const r = await db.query<{ typname: string }>(`select typname from pg_type where oid = $1::regtype`, [formatted.replace(/^public\./, 'public.')])
      return r.rows[0]!.typname
    }

    let out = `// Generated by scripts/gen-db-types.ts — do not edit by hand.\n`
    out += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\n\n`
    out += `export type Database = {\n  public: {\n    Tables: {\n`
    for (const [name, columns] of tables) {
      const row = columns.map((c) => `          ${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n')
      const ins = columns.map((c) => `          ${c.column_name}${c.is_nullable === 'YES' || c.column_default !== null ? '?' : ''}: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n')
      const upd = columns.map((c) => `          ${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n')
      out += `      ${name}: {\n        Row: {\n${row}\n        }\n        Insert: {\n${ins}\n        }\n        Update: {\n${upd}\n        }\n        Relationships: []\n      }\n`
    }
    out += `    }\n    Views: { [_ in never]: never }\n    Functions: {\n`
    for (const f of fns) {
      const inNames = (f.arg_names ?? []).slice(0, f.arg_types.length)
      const args: string[] = []
      for (let i = 0; i < f.arg_types.length; i++) {
        const optional = i >= f.arg_types.length - f.n_defaults
        args.push(`${inNames[i]}${optional ? '?' : ''}: ${tsType(await argUdt(f.arg_types[i]!))}`)
      }
      let ret: string
      if (f.out_names && f.out_names.length) {
        ret = `{\n${f.out_names.map((n, i) => `            ${n}: ${tsType(f.out_types![i]!)} | null`).join('\n')}\n          }[]`
      } else {
        ret = tsType(f.ret_type) + (f.retset ? '[]' : '')
      }
      out += `      ${f.name}: {\n        Args: ${args.length ? `{ ${args.join('; ')} }` : 'Record<PropertyKey, never>'}\n        Returns: ${ret}\n      }\n`
    }
    out += `    }\n    Enums: {\n`
    for (const e of enums) out += `      ${e.name}: ${e.values.map((v) => `'${v}'`).join(' | ')}\n`
    out += `    }\n    CompositeTypes: { [_ in never]: never }\n  }\n}\n\n`
    out += `type PublicSchema = Database['public']\nexport type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row']\n`
    out += `export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert']\n`
    out += `export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update']\n`
    out += `export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T]\n`
    out += `export type RpcReturns<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T]['Returns']\n`

    fs.mkdirSync(path.join(root, 'src/types'), { recursive: true })
    fs.writeFileSync(path.join(root, 'src/types/database.ts'), out)
    console.log(`Wrote src/types/database.ts (${tables.size} tables, ${fns.length} functions, ${enums.length} enums)`)
  } finally {
    await db.end()
    await server.stop()
    fs.rmSync(dir, { recursive: true, force: true })
  }
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
